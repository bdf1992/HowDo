class TreatmentDefinitionTests(unittest.TestCase):
    """The contract the adapter implements has to keep saying what it promised."""

    def test_the_treatment_definition_exists_and_names_its_arms(self):
        text = _flatten(TREATMENT.read_text(encoding="utf-8"))
        for arm in ("h0", "h1", "h2"):
            self.assertIn(arm, text)
        self.assertIn("raw agent", text)
        self.assertIn("per-trial reconnaissance", text)

    def test_it_prohibits_persistent_context_and_gives_the_reason(self):
        text = _flatten(TREATMENT.read_text(encoding="utf-8"))
        self.assertIn("persistent", text)
        self.assertIn("independence", text)

    def test_it_records_the_confound_rather_than_hiding_it(self):
        text = _flatten(TREATMENT.read_text(encoding="utf-8"))
        self.assertIn("cannot attribute", text)
        self.assertIn("reconnaissance", text)

    def test_it_states_that_a_null_does_not_falsify_all_of_how_do(self):
        text = _flatten(TREATMENT.read_text(encoding="utf-8"))
        self.assertIn("not how do as a whole", text)

    def test_it_keeps_the_promotion_boundary(self):
        text = _flatten(TREATMENT.read_text(encoding="utf-8"))
        self.assertIn("not how do 0.9", text)
        self.assertIn("branch may exist before the evidence earns the core", text)

    def test_the_procedure_draws_the_observation_boundary(self):
        text = _flatten(PROCEDURE.read_text(encoding="utf-8"))
        self.assertIn("observations, not conclusions", text)
        self.assertIn("task learning", text)

    def test_both_documents_admit_what_they_do_not_check(self):
        for document in (TREATMENT, PROCEDURE):
            text = _flatten(document.read_text(encoding="utf-8"))
            self.assertIn("structural", text, f"{document.name} overclaims completion")

    def test_the_experiment_does_not_ship_in_the_skill_payload(self):
        sys.path.insert(0, str(ROOT))
        import install  # noqa: E402

        self.assertNotIn("experiment", install.PAYLOAD)


